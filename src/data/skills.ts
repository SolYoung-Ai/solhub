export type SkillCategory =
  | "engineering"
  | "design"
  | "docs"
  | "writing"
  | "research"
  | "automation"
  | "growth"
  | "collections";

export type SkillKind = "skill" | "collection";

export interface SkillCategoryDef {
  slug: SkillCategory;
  name: string;
  nameEn: string;
}

export const skillCategories: SkillCategoryDef[] = [
  { slug: "engineering", name: "开发工程", nameEn: "Engineering" },
  { slug: "design", name: "设计创意", nameEn: "Design & Creative" },
  { slug: "docs", name: "文档办公", nameEn: "Documents" },
  { slug: "writing", name: "内容写作", nameEn: "Writing" },
  { slug: "research", name: "数据科研", nameEn: "Research & Data" },
  { slug: "automation", name: "效率自动化", nameEn: "Automation" },
  { slug: "growth", name: "营销增长", nameEn: "Growth" },
  { slug: "collections", name: "合集资源", nameEn: "Collections" },
];

export function skillCategoryName(slug: string, locale: "zh" | "en" = "zh"): string {
  const c = skillCategories.find((x) => x.slug === slug);
  return c ? (locale === "en" ? c.nameEn : c.name) : slug;
}

export interface SkillItem {
  /** 列表中的唯一标识 */
  id: string;
  /** 展示名称：单个 Skill 用 skill 名，合集用仓库名 */
  name: string;
  /** 所属仓库 / 站点，如 "vercel-labs/skills" */
  repo: string;
  /** skill = 单个技能；collection = 技能合集 / 框架 / 目录 */
  kind: SkillKind;
  category: SkillCategory;
  description: string;
  descriptionEn: string;
  tags: string[];
  platforms: string[];
  /** 主链接（skills.sh 详情页或 GitHub 仓库） */
  url: string;
  /** GitHub 仓库地址（可选，卡片上的第二个入口） */
  github?: string;
  /** 一行安装命令 */
  install?: string;
  /** skills.sh 全时段安装量 */
  installs?: number;
  /** GitHub Stars */
  stars?: number;
  /** 官方出品 */
  official?: boolean;
  /** 综合热度 0~100，用于默认排序（按安装量 / Star 量级人工归一化） */
  heat: number;
}

