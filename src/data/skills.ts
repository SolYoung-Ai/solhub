export type SkillCategory =
  | "engineering"
  | "design"
  | "docs"
  | "writing"
  | "research"
  | "automation"
  | "growth"
  | "collections";

export type SkillKind = "skill" | "collection";

export interface SkillCategoryDef {
  slug: SkillCategory;
  name: string;
  nameEn: string;
}

